#!/usr/bin/env python3
"""Generate src/directions.js from a local copy of the design-taste-frontend skill (tasteskill v2).

usage: python3 tools/import_taste.py <path to design-taste-frontend folder>

Only the fields the studio shows are kept. The skill itself is not copied into this repo;
it stays installed separately and does the actual build.
"""
import json, sys
from pathlib import Path

src = Path(sys.argv[1]) if len(sys.argv) > 1 else sys.exit(__doc__)
dirs = json.loads((src / "library" / "directions.json").read_text(encoding="utf-8"))
keep = ["id", "name", "sectors", "tones", "needs", "idea", "composition", "typography", "colour", "imagery", "pitfalls"]
out = [{k: d.get(k) for k in keep} for d in dirs]

sectors = ["saas", "dev-tool", "ai-product", "consumer-app", "finance", "agency", "studio-portfolio", "personal-portfolio",
           "ecommerce", "physical-product", "fashion", "hospitality", "restaurant", "real-estate", "architecture", "event",
           "health", "education", "nonprofit", "culture", "music", "other"]
roles = ["features", "showcase", "how-it-works", "testimonial", "proof", "stats", "pricing", "faq", "cta", "footer",
         "intro", "about", "work", "gallery", "list", "contact"]

js = (
    "/* Directions from tasteskill v2 (design-taste-frontend), an open-source skill distilled from a study of\n"
    "   247 curated gallery sites. Trimmed copy for the studio's picker; generated by tools/import_taste.py.\n"
    "   The skill itself performs the build, inspection and critique. */\n"
    f"const TASTE_DIRECTIONS = {json.dumps(out, ensure_ascii=False, indent=0)};\n"
    f"const TASTE_SECTORS = {json.dumps(sectors)};\n"
    f"const TASTE_ROLES = {json.dumps(roles)};\n"
)
dest = Path(__file__).resolve().parent.parent / "src" / "directions.js"
dest.write_text(js, encoding="utf-8")
print(f"wrote {dest} ({len(out)} directions, {len(js) // 1024} KB)")
